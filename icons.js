  function resolveName(name) {
    if (!name) return 'book-open';
    var clean = String(name).trim();
    if (PATHS[clean]) return clean;
    if (EMOJI_TO_ICON[clean]) return EMOJI_TO_ICON[clean];
    // strip variation selector FE0F
    var stripped = clean.replace(/\uFE0F/g, '');
    if (EMOJI_TO_ICON[stripped]) return EMOJI_TO_ICON[stripped];
    return 'sparkles';
  }

  function uiIcon(name, size, cls) {
    var sz = size || 16;
    var key = resolveName(name);
    var body = PATHS[key] || PATHS['sparkles'];
    var c = cls ? 'ui-icon ' + cls : 'ui-icon';
    return '<svg class="' + c + '" width="' + sz + '" height="' + sz + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.85" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + body + '</svg>';
  }

  function hydrateIcons(root) {
    var scope = root || document;
    var nodes = scope.querySelectorAll('[data-icon]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var name = el.getAttribute('data-icon');
      var sz = parseInt(el.getAttribute('data-size') || '16', 10) || 16;
      var cls = el.getAttribute('data-icon-class') || '';
      el.outerHTML = uiIcon(name, sz, cls);
    }
  }

